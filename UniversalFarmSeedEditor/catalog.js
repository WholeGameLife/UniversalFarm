// Standalone snapshot. No game imports or runtime dependencies.
const CROP_SCHEMA_VERSION = 1;
const SOIL_IDS = ['loam', 'sand', 'clay', 'peat'];
const BIOME_IDS = ['temperate', 'desert', 'frozen', 'volcanic', 'void'];
const VISUAL_SHAPES = ['wheat', 'bush', 'melon', 'root', 'vine'];

function validateCropCatalog(crops) {
  const errors = [];
  if (!Array.isArray(crops) || !crops.length) return ['至少需要一种作物，数据必须为数组'];
  const ids = new Set(), itemIds = new Set();
  const idPattern = /^[a-z][a-z0-9_]*$/;
  for (const [i, c] of crops.entries()) {
    const label = c?.id || `第 ${i + 1} 项`;
    const fail = (message) => errors.push(`${label}: ${message}`);
    if (!c || typeof c !== 'object' || Array.isArray(c)) { fail('作物必须为对象'); continue; }
    if (typeof c.id !== 'string' || !idPattern.test(c.id)) fail('ID 只能包含小写英文、数字、下划线，并以字母开头');
    if (ids.has(c.id)) fail('作物 ID 重复');
    ids.add(c.id);
    for (const key of ['name', 'description', 'seedIcon']) if (typeof c[key] !== 'string' || !c[key].trim()) fail(`缺少 ${key}`);
    const integer = (value, min, name) => { if (!Number.isSafeInteger(value) || value < min) fail(`${name} 必须为不小于 ${min} 的整数`); };
    integer(c.seedPrice, 1, '种子价格');
    integer(c.growDays, 1, '成熟天数');
    integer(c.regrowDays, 0, '再生天数');
    integer(c.waterIntervalDays, 1, '浇水间隔');
    integer(c.maxDryDays, 0, '连续缺水容忍天数');
    if (!Array.isArray(c.stages) || c.stages.length < 2 || !c.stages.every((s) => typeof s === 'string' && s.trim())) fail('至少需要幼苗和成熟两个阶段图标');
    if (!Array.isArray(c.stageDays) || c.stageDays.length !== (c.stages?.length ?? 0) - 1
      || !c.stageDays.every((n) => Number.isSafeInteger(n) && n > 0) || c.stageDays.reduce((a, b) => a + b, 0) !== c.growDays) fail('阶段天数必须为正整数，数量为阶段数减一，合计等于成熟天数');
    if (!c.harvest || typeof c.harvest !== 'object') fail('缺少收获数据');
    else {
      integer(c.harvest.min, 1, '最低产量'); integer(c.harvest.max, 1, '最高产量'); integer(c.harvest.sellPrice, 1, '基础售价');
      if (c.harvest.max < c.harvest.min) fail('最高产量小于最低产量');
      if (typeof c.harvest.icon !== 'string' || !c.harvest.icon.trim()) fail('缺少收获图标');
    }
    for (const id of [c.seed, c.harvest?.item, ...(c.harvest?.item ? [c.harvest.item + '_silver', c.harvest.item + '_gold'] : [])]) {
      if (typeof id !== 'string' || !idPattern.test(id)) fail('种子/收获物 ID 格式无效');
      if (itemIds.has(id)) fail(`物品 ID 重复: ${id}`);
      itemIds.add(id);
    }
    const r = c.requirements;
    if (!r || !Array.isArray(r.soils) || !r.soils.length || r.soils.some((s) => !SOIL_IDS.includes(s))) fail('土地需求需包含有效土壤类型');
    if (!r || !Array.isArray(r.biomes) || r.biomes.some((s) => !BIOME_IDS.includes(s))) fail('群系需求无效');
    for (const [key, min, max] of [['temperature', -100, 100], ['moisture', 0, 100]]) {
      const range = r?.[key];
      if (!Array.isArray(range) || range.length !== 2 || !range.every((v) => Number.isFinite(v) && v >= min && v <= max) || range[0] > range[1]) fail(`${key} 必须为从小到大的有效范围`);
    }
    const a = c.availability;
    if (!a || typeof a.shop !== 'boolean' || !Array.isArray(a.sources) || !a.sources.every((s) => typeof s === 'string')) fail('获取方式无效');
    if (a?.requires !== null && (typeof a?.requires !== 'string' || !idPattern.test(a.requires))) fail('科技条件需为有效 ID 或 null');
    const spawn = a?.wild;
    if (!spawn || !Array.isArray(spawn.biomes) || spawn.biomes.some((s) => !BIOME_IDS.includes(s))
      || !Number.isFinite(spawn.chance) || spawn.chance < 0 || spawn.chance > 1) fail('野外生成群系/概率无效');
    if (!c.uses || !Array.isArray(c.uses.tags) || !c.uses.tags.every((s) => typeof s === 'string') || !Array.isArray(c.uses.processing)) fail('用途数据无效');
    integer(c.uses?.foodEnergy, 0, '食用体力');
    for (const recipe of Array.isArray(c.uses?.processing) ? c.uses.processing : []) {
      if (!recipe || typeof recipe !== 'object') { fail('加工配方必须为对象'); continue; }
      for (const key of ['id', 'machine', 'output']) if (typeof recipe[key] !== 'string' || !idPattern.test(recipe[key])) fail(`加工 ${key} 无效`);
      if (typeof recipe.name !== 'string' || !recipe.name.trim()) fail('加工用途需要名称');
      integer(recipe.inputCount, 1, '加工投入'); integer(recipe.outputCount, 1, '加工产出');
      if (!Number.isFinite(recipe.hours) || recipe.hours <= 0) fail('加工小时数必须大于 0');
    }
    if (!c.visual || !VISUAL_SHAPES.includes(c.visual.shape)) fail('作物模型类型无效');
    for (const key of ['leaf', 'fruit']) if (!/^#[0-9a-f]{6}$/i.test(c.visual?.[key] ?? '')) fail(`模型 ${key} 需要 #RRGGBB 颜色`);
  }
  return errors;
}

function cropModuleSource(crops) {
  const errors = validateCropCatalog(crops);
  if (errors.length) throw new Error(errors.join('\n'));
  return `// Crop catalog v${CROP_SCHEMA_VERSION}. Generated by the standalone seed editor.\nexport const crops = ${JSON.stringify(crops, null, 2)};\n`;
}

function parseCropCatalog(text) {
  const cleaned = text.replace(/^\uFEFF/, '').replace(/^\s*\/\/[^\n]*(\n|$)/, '').trim();
  const json = cleaned.startsWith('export const crops =') ? cleaned.slice('export const crops ='.length).trim().replace(/;\s*$/, '') : cleaned;
  const parsed = JSON.parse(json);
  if (parsed && !Array.isArray(parsed) && parsed.schemaVersion !== CROP_SCHEMA_VERSION) throw new Error('不支持的作物数据版本');
  const crops = Array.isArray(parsed) ? parsed : parsed.crops;
  const errors = validateCropCatalog(crops);
  if (errors.length) throw new Error(errors.join('\n'));
  return crops;
}

